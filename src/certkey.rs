//! Certificate private keys: which kinds the platform will use, how a fresh one is generated, and
//! how one is put on disk.
//!
//! ## Policy ([`KeyPolicy`])
//! New certificate keys are **ECDSA P-256** (the default) or **P-384**. RSA is accepted only at
//! 3072 bits or more, and only for a key that arrives from outside (this crate never generates
//! one). P-521, Ed25519 (no publicly trusted CA issues Ed25519 subscriber certificates), DSA, a
//! short RSA key or anything this reader does not recognise is refused. The policy is applied
//! where a key is chosen ([`KeyPolicy::check_alg`]), where material is installed
//! ([`KeyPolicy::check_pkcs8_pem`], called by the renewal engine and by `FileCertStore::put`) and
//! therefore on whatever an issuer hands back.
//!
//! ## Generation ([`CertKeyGen`])
//! A key is generated by `aws-lc-rs` from the system RNG (the FIPS-validated generator with the
//! `fips` feature) — once per order, **before** the order is placed, so an RNG failure costs the
//! CA no authorization and the validation rate limit nothing. The trait is the seam tests use to
//! make generation fail; a failure is an error the caller returns, never a fallback.
//!
//! ## Persistence ([`write_private_atomic`])
//! A key file is created exclusively (`O_EXCL`, so a stale or planted file or symlink at the
//! temporary name is an error, not something we write through), with mode 0600 *at creation* (no
//! window in which it is readable by anyone else), fsynced, renamed over the destination and the
//! directory fsynced. A reader sees the old file or the new one, never a torn one.

use std::fmt;
use std::io::Write as _;
use std::path::Path;

use aws_lc_rs::signature::{EcdsaKeyPair, EcdsaSigningAlgorithm, KeyPair, ECDSA_P256_SHA256_FIXED_SIGNING, ECDSA_P384_SHA384_FIXED_SIGNING};

use crate::acme::der;

/// A certificate key algorithm this crate can generate and put in a CSR.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum KeyAlg {
    /// ECDSA over NIST P-256 with SHA-256. The default: smallest, fastest, universally served.
    #[default]
    P256,
    /// ECDSA over NIST P-384 with SHA-384.
    P384,
}

// OID contents (without tag/length).
const OID_EC_PUBLIC_KEY: &[u8] = &[0x2a, 0x86, 0x48, 0xce, 0x3d, 0x02, 0x01]; // 1.2.840.10045.2.1
const OID_PRIME256V1: &[u8] = &[0x2a, 0x86, 0x48, 0xce, 0x3d, 0x03, 0x01, 0x07]; // 1.2.840.10045.3.1.7
const OID_SECP384R1: &[u8] = &[0x2b, 0x81, 0x04, 0x00, 0x22]; // 1.3.132.0.34
const OID_SECP521R1: &[u8] = &[0x2b, 0x81, 0x04, 0x00, 0x23]; // 1.3.132.0.35
const OID_ECDSA_SHA256: &[u8] = &[0x2a, 0x86, 0x48, 0xce, 0x3d, 0x04, 0x03, 0x02]; // 1.2.840.10045.4.3.2
const OID_ECDSA_SHA384: &[u8] = &[0x2a, 0x86, 0x48, 0xce, 0x3d, 0x04, 0x03, 0x03]; // 1.2.840.10045.4.3.3
const OID_RSA_ENCRYPTION: &[u8] = &[0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d, 0x01, 0x01, 0x01]; // 1.2.840.113549.1.1.1
const OID_ED25519: &[u8] = &[0x2b, 0x65, 0x70]; // 1.3.101.112

impl KeyAlg {
    pub(crate) fn signing(self) -> &'static EcdsaSigningAlgorithm {
        match self {
            KeyAlg::P256 => &ECDSA_P256_SHA256_FIXED_SIGNING,
            KeyAlg::P384 => &ECDSA_P384_SHA384_FIXED_SIGNING,
        }
    }

    pub(crate) fn curve_oid(self) -> &'static [u8] {
        match self {
            KeyAlg::P256 => OID_PRIME256V1,
            KeyAlg::P384 => OID_SECP384R1,
        }
    }

    pub(crate) fn signature_oid(self) -> &'static [u8] {
        match self {
            KeyAlg::P256 => OID_ECDSA_SHA256,
            KeyAlg::P384 => OID_ECDSA_SHA384,
        }
    }

    /// Bytes in one signature component (`r` or `s`).
    pub(crate) fn component_len(self) -> usize {
        match self {
            KeyAlg::P256 => 32,
            KeyAlg::P384 => 48,
        }
    }

    /// `ecdsa-with-SHA*` / curve identifier: `P-256`, `P-384`.
    #[must_use]
    pub fn name(self) -> &'static str {
        match self {
            KeyAlg::P256 => "P-256",
            KeyAlg::P384 => "P-384",
        }
    }
}

/// What kind of private key a PKCS#8 blob holds, as far as the policy cares.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum KeyKind {
    Ec(EcCurve),
    /// RSA with this modulus size in bits.
    Rsa { bits: u32 },
    Ed25519,
    /// Not PKCS#8, or an algorithm this reader does not know.
    Unknown,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EcCurve {
    P256,
    P384,
    P521,
    /// Some other (or explicitly parameterised) curve.
    Other,
}

/// Read the algorithm out of a PKCS#8 `PrivateKeyInfo` DER.
#[must_use]
pub fn inspect_pkcs8(pkcs8: &[u8]) -> KeyKind {
    inspect(pkcs8).unwrap_or(KeyKind::Unknown)
}

fn inspect(pkcs8: &[u8]) -> Option<KeyKind> {
    if pkcs8.len() > 16 * 1024 {
        return None;
    }
    let (0x30, info, rest) = der::read(pkcs8)? else { return None };
    if !rest.is_empty() {
        return None;
    }
    let (0x02, _version, after) = der::read(info)? else { return None };
    let (0x30, alg, after) = der::read(after)? else { return None };
    let (0x04, key, _) = der::read(after)? else { return None };
    let (0x06, oid, params) = der::read(alg)? else { return None };
    if oid == OID_EC_PUBLIC_KEY {
        let (0x06, curve, _) = der::read(params)? else { return Some(KeyKind::Ec(EcCurve::Other)) };
        return Some(KeyKind::Ec(match curve {
            c if c == OID_PRIME256V1 => EcCurve::P256,
            c if c == OID_SECP384R1 => EcCurve::P384,
            c if c == OID_SECP521R1 => EcCurve::P521,
            _ => EcCurve::Other,
        }));
    }
    if oid == OID_RSA_ENCRYPTION {
        // RSAPrivateKey ::= SEQUENCE { version INTEGER, modulus INTEGER, ... }
        let (0x30, rsa, _) = der::read(key)? else { return None };
        let (0x02, _, after) = der::read(rsa)? else { return None };
        let (0x02, modulus, _) = der::read(after)? else { return None };
        let significant = modulus.iter().position(|b| *b != 0).map_or(&[][..], |i| &modulus[i..]);
        let first = *significant.first()?;
        let bits = u32::try_from(significant.len()).ok()?.checked_mul(8)?.checked_sub(first.leading_zeros())?;
        return Some(KeyKind::Rsa { bits });
    }
    if oid == OID_ED25519 {
        return Some(KeyKind::Ed25519);
    }
    Some(KeyKind::Unknown)
}

/// Why a key was refused.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum KeyRefusal {
    RsaTooSmall { bits: u32, min: u32 },
    CurveNotAllowed(&'static str),
    AlgorithmNotAllowed(&'static str),
    NoKey,
    Unrecognised,
}

impl fmt::Display for KeyRefusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            KeyRefusal::RsaTooSmall { bits, min } => write!(f, "an RSA-{bits} key is below the {min}-bit minimum"),
            KeyRefusal::CurveNotAllowed(c) => write!(f, "the {c} curve is not an allowed certificate key"),
            KeyRefusal::AlgorithmNotAllowed(a) => write!(f, "{a} is not an allowed certificate key algorithm"),
            KeyRefusal::NoKey => write!(f, "no PKCS#8 private key"),
            KeyRefusal::Unrecognised => write!(f, "the private key is not a recognised PKCS#8 key"),
        }
    }
}

impl std::error::Error for KeyRefusal {}

/// Which certificate keys are acceptable. Cheap to copy; the defaults are the platform policy.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct KeyPolicy {
    /// Accept P-384 as well as P-256.
    pub allow_p384: bool,
    /// Smallest RSA modulus accepted for a key that arrives from outside.
    pub min_rsa_bits: u32,
}

impl Default for KeyPolicy {
    fn default() -> Self {
        KeyPolicy { allow_p384: true, min_rsa_bits: 3072 }
    }
}

impl KeyPolicy {
    /// Whether `kind` meets the policy.
    ///
    /// # Errors
    /// [`KeyRefusal`] naming why not.
    pub fn check(&self, kind: &KeyKind) -> Result<(), KeyRefusal> {
        match kind {
            KeyKind::Ec(EcCurve::P256) => Ok(()),
            KeyKind::Ec(EcCurve::P384) if self.allow_p384 => Ok(()),
            KeyKind::Ec(EcCurve::P384) => Err(KeyRefusal::CurveNotAllowed("P-384")),
            KeyKind::Ec(EcCurve::P521) => Err(KeyRefusal::CurveNotAllowed("P-521")),
            KeyKind::Ec(EcCurve::Other) => Err(KeyRefusal::CurveNotAllowed("an unrecognised")),
            KeyKind::Rsa { bits } if *bits >= self.min_rsa_bits => Ok(()),
            KeyKind::Rsa { bits } => Err(KeyRefusal::RsaTooSmall { bits: *bits, min: self.min_rsa_bits }),
            KeyKind::Ed25519 => Err(KeyRefusal::AlgorithmNotAllowed("Ed25519")),
            KeyKind::Unknown => Err(KeyRefusal::Unrecognised),
        }
    }

    /// Whether this client may generate keys of `alg`.
    ///
    /// # Errors
    /// P-384 when the policy does not allow it.
    pub fn check_alg(&self, alg: KeyAlg) -> Result<(), KeyRefusal> {
        match alg {
            KeyAlg::P256 => Ok(()),
            KeyAlg::P384 if self.allow_p384 => Ok(()),
            KeyAlg::P384 => Err(KeyRefusal::CurveNotAllowed("P-384")),
        }
    }

    /// Check the first `PRIVATE KEY` block of `key_pem`.
    ///
    /// # Errors
    /// No key block, an unrecognised key, or a key the policy refuses.
    pub fn check_pkcs8_pem(&self, key_pem: &str) -> Result<KeyKind, KeyRefusal> {
        let der = crate::pem::blocks(key_pem, "PRIVATE KEY").into_iter().next().ok_or(KeyRefusal::NoKey)?;
        let kind = inspect_pkcs8(&der);
        self.check(&kind)?;
        Ok(kind)
    }
}

/// Key generation failed (the system RNG, or the module refusing).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct KeyGenError(pub String);

impl fmt::Display for KeyGenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "certificate key generation failed: {}", self.0)
    }
}

impl std::error::Error for KeyGenError {}

/// Generates certificate private keys. The seam between the ACME client and the RNG: production
/// is [`OsCertKeyGen`]; tests substitute one that fails to prove issuance stops.
pub trait CertKeyGen: Send + Sync + fmt::Debug {
    /// A fresh key of `alg`.
    ///
    /// # Errors
    /// The generator could not produce a key. The caller returns the error; it does not retry
    /// with another generator.
    fn generate(&self, alg: KeyAlg) -> Result<EcdsaKeyPair, KeyGenError>;
}

/// `aws-lc-rs` key generation from the system RNG.
#[derive(Clone, Copy, Debug, Default)]
pub struct OsCertKeyGen;

impl CertKeyGen for OsCertKeyGen {
    fn generate(&self, alg: KeyAlg) -> Result<EcdsaKeyPair, KeyGenError> {
        EcdsaKeyPair::generate(alg.signing()).map_err(|_| KeyGenError("the system RNG or the crypto module failed".into()))
    }
}

/// The complete `SubjectPublicKeyInfo` DER for `pair`.
#[must_use]
pub fn spki_der(pair: &EcdsaKeyPair, alg: KeyAlg) -> Vec<u8> {
    der::seq(&[ec_algorithm_identifier(alg), der::bit_string(pair.public_key().as_ref())])
}

pub(crate) fn ec_algorithm_identifier(alg: KeyAlg) -> Vec<u8> {
    der::seq(&[der::tlv(0x06, OID_EC_PUBLIC_KEY), der::tlv(0x06, alg.curve_oid())])
}

/// Write `contents` to `path` as a secret: created exclusively next to `path` with mode 0600,
/// fsynced, renamed into place, directory fsynced. The temporary name is random, so a stale file
/// from a crashed write never blocks (or is reused by) a later one, and a file or symlink planted
/// at a guessable name is never written through.
///
/// # Errors
/// Any I/O failure. On error `path` still holds what it held before and the temporary file is
/// removed.
pub fn write_private_atomic(path: &Path, contents: &[u8]) -> std::io::Result<()> {
    let dir = path.parent().filter(|p| !p.as_os_str().is_empty()).unwrap_or_else(|| Path::new("."));
    let name = path.file_name().and_then(|n| n.to_str()).ok_or_else(|| std::io::Error::other("secret path has no file name"))?;
    let suffix = crate::entropy::random_hex(8).map_err(std::io::Error::other)?;
    let tmp = dir.join(format!(".{name}.{suffix}.tmp"));
    let result = (|| {
        let mut opts = std::fs::OpenOptions::new();
        opts.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            opts.mode(0o600);
        }
        let mut f = opts.open(&tmp)?;
        f.write_all(contents)?;
        f.sync_all()?;
        drop(f);
        std::fs::rename(&tmp, path)?;
        #[cfg(unix)]
        std::fs::File::open(dir).and_then(|d| d.sync_all())?;
        Ok(())
    })();
    if result.is_err() {
        let _ = std::fs::remove_file(&tmp);
    }
    result
}

/// Whether `path` is readable by anyone but its owner (unix; always `false` elsewhere).
#[must_use]
pub fn is_group_or_world_accessible(path: &Path) -> bool {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::metadata(path).is_ok_and(|m| m.permissions().mode() & 0o077 != 0)
    }
    #[cfg(not(unix))]
    {
        let _ = path;
        false
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use aws_lc_rs::rsa::{KeyPair as RsaKeyPair, KeySize};
    use aws_lc_rs::encoding::AsDer;
    use aws_lc_rs::signature::{Ed25519KeyPair, ECDSA_P521_SHA512_FIXED_SIGNING};

    fn pem_of(der: &[u8]) -> String {
        crate::acme::pem_wrap("PRIVATE KEY", der)
    }

    fn ec_pem(alg: &'static EcdsaSigningAlgorithm) -> String {
        let pair = EcdsaKeyPair::generate(alg).unwrap();
        pem_of(pair.to_pkcs8v1().unwrap().as_ref())
    }

    fn rsa_pem(size: KeySize) -> String {
        let pair = RsaKeyPair::generate(size).unwrap();
        let pkcs8 = AsDer::<aws_lc_rs::encoding::Pkcs8V1Der>::as_der(&pair).unwrap();
        pem_of(pkcs8.as_ref())
    }

    #[test]
    fn the_policy_accepts_p256_and_p384_and_rsa_3072_and_refuses_everything_else() {
        let p = KeyPolicy::default();
        assert_eq!(p.check_pkcs8_pem(&ec_pem(&ECDSA_P256_SHA256_FIXED_SIGNING)).unwrap(), KeyKind::Ec(EcCurve::P256));
        assert_eq!(p.check_pkcs8_pem(&ec_pem(&ECDSA_P384_SHA384_FIXED_SIGNING)).unwrap(), KeyKind::Ec(EcCurve::P384));
        assert_eq!(p.check_pkcs8_pem(&rsa_pem(KeySize::Rsa3072)).unwrap(), KeyKind::Rsa { bits: 3072 });

        let short = p.check_pkcs8_pem(&rsa_pem(KeySize::Rsa2048)).unwrap_err();
        assert_eq!(short, KeyRefusal::RsaTooSmall { bits: 2048, min: 3072 });
        assert_eq!(p.check_pkcs8_pem(&ec_pem(&ECDSA_P521_SHA512_FIXED_SIGNING)).unwrap_err(), KeyRefusal::CurveNotAllowed("P-521"));
        let ed = pem_of(Ed25519KeyPair::generate_pkcs8(&aws_lc_rs::rand::SystemRandom::new()).unwrap().as_ref());
        assert_eq!(p.check_pkcs8_pem(&ed).unwrap_err(), KeyRefusal::AlgorithmNotAllowed("Ed25519"));
        assert_eq!(p.check_pkcs8_pem("no key here").unwrap_err(), KeyRefusal::NoKey);
        assert_eq!(p.check_pkcs8_pem(&pem_of(&[0x30, 0x03, 0x02, 0x01, 0x00])).unwrap_err(), KeyRefusal::Unrecognised);
        // A policy without P-384 refuses it, both as a key and as a generation request.
        let strict = KeyPolicy { allow_p384: false, ..p };
        assert!(strict.check_pkcs8_pem(&ec_pem(&ECDSA_P384_SHA384_FIXED_SIGNING)).is_err());
        assert!(strict.check_alg(KeyAlg::P384).is_err() && strict.check_alg(KeyAlg::P256).is_ok());
        // The minimum is a knob, not a constant: a 4096 floor refuses 3072.
        assert!(KeyPolicy { min_rsa_bits: 4096, ..p }.check_pkcs8_pem(&rsa_pem(KeySize::Rsa3072)).is_err());
    }

    #[test]
    fn generated_keys_are_distinct_and_the_spki_matches_the_key() {
        let g = OsCertKeyGen;
        let (a, b) = (g.generate(KeyAlg::P256).unwrap(), g.generate(KeyAlg::P256).unwrap());
        assert_ne!(a.public_key().as_ref(), b.public_key().as_ref());
        let p384 = g.generate(KeyAlg::P384).unwrap();
        assert_eq!(p384.public_key().as_ref().len(), 1 + 2 * 48);
        let spki = spki_der(&a, KeyAlg::P256);
        let (tag, _, rest) = der::read(&spki).unwrap();
        assert_eq!((tag, rest.len()), (0x30, 0));
    }

    #[test]
    fn a_secret_is_written_atomically_with_mode_0600_even_over_a_permissive_file() {
        use std::os::unix::fs::PermissionsExt;
        let dir = tempdir("atomic");
        let path = dir.join("key.pem");
        // A pre-existing world-readable file at the destination: the replacement must not inherit it.
        std::fs::write(&path, b"old").unwrap();
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o644)).unwrap();
        write_private_atomic(&path, b"new secret").unwrap();
        assert_eq!(std::fs::read(&path).unwrap(), b"new secret");
        assert_eq!(std::fs::metadata(&path).unwrap().permissions().mode() & 0o777, 0o600);
        assert!(!is_group_or_world_accessible(&path));
        // No temporary file is left behind.
        let leftovers: Vec<_> = std::fs::read_dir(&dir).unwrap().map(|e| e.unwrap().file_name()).filter(|n| n != "key.pem").collect();
        assert!(leftovers.is_empty(), "{leftovers:?}");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn a_failed_write_leaves_the_old_secret_and_no_temporary_file() {
        let dir = tempdir("failwrite");
        let path = dir.join("key.pem");
        write_private_atomic(&path, b"first").unwrap();
        // Make the rename fail: the destination is a non-empty directory.
        let blocked = dir.join("blocked");
        std::fs::create_dir_all(blocked.join("inner")).unwrap();
        assert!(write_private_atomic(&blocked, b"x").is_err());
        assert_eq!(std::fs::read(&path).unwrap(), b"first");
        let tmp_files: Vec<_> = std::fs::read_dir(&dir).unwrap().map(|e| e.unwrap().file_name().to_string_lossy().into_owned()).filter(|n| n.ends_with(".tmp")).collect();
        assert!(tmp_files.is_empty(), "temporary file leaked: {tmp_files:?}");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn a_planted_file_at_a_guessable_temporary_name_is_never_written_through() {
        let dir = tempdir("planted");
        let victim = dir.join("victim");
        std::fs::write(&victim, b"untouched").unwrap();
        // The temp name is random; plant a symlink at the *old* fixed names a naive writer would use.
        for guess in ["key.pem.tmp", ".key.pem.tmp", "key.tmp"] {
            std::os::unix::fs::symlink(&victim, dir.join(guess)).unwrap();
        }
        write_private_atomic(&dir.join("key.pem"), b"secret").unwrap();
        assert_eq!(std::fs::read(&victim).unwrap(), b"untouched");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn a_reader_never_sees_a_torn_secret() {
        let dir = tempdir("torn");
        let path = dir.join("key.pem");
        let (old, new) = (vec![b'a'; 64 * 1024], vec![b'b'; 64 * 1024]);
        write_private_atomic(&path, &old).unwrap();
        let reader = {
            let (path, old, new) = (path.clone(), old.clone(), new.clone());
            std::thread::spawn(move || {
                let started = std::time::Instant::now();
                while started.elapsed() < Duration::from_millis(400) {
                    let seen = std::fs::read(&path).unwrap();
                    assert!(seen == old || seen == new, "torn read of {} bytes", seen.len());
                }
            })
        };
        for i in 0..30 {
            write_private_atomic(&path, if i % 2 == 0 { &new } else { &old }).unwrap();
        }
        reader.join().unwrap();
        let _ = std::fs::remove_dir_all(&dir);
    }

    use std::time::Duration;

    fn tempdir(tag: &str) -> std::path::PathBuf {
        let p = std::env::temp_dir().join(format!("certkey-{tag}-{}", crate::entropy::random_hex(6).unwrap()));
        std::fs::create_dir_all(&p).unwrap();
        p
    }
}
