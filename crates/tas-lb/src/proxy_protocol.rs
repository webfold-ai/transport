//! `PROXY` protocol v2 (the `HAProxy` binary header), encode and decode.
//!
//! Only v2 is spoken. v1 is a text line that any HTTP-ish client can type by accident or on
//! purpose, which is exactly the property a trust-boundary header must not have; v2 starts with
//! a 12-byte signature containing NUL and CR/LF bytes that no sane protocol begins with.
//!
//! ## Wire format (all multi-byte fields big-endian)
//!
//! ```text
//! 0..12   signature  0D 0A 0D 0A 00 0D 0A 51 55 49 54 0A
//! 12      version<<4 | command      (0x20 LOCAL, 0x21 PROXY)
//! 13      family<<4  | protocol     (family 0 UNSPEC, 1 INET, 2 INET6, 3 UNIX; proto 0/1 STREAM/2 DGRAM)
//! 14..16  length of everything after these 16 bytes
//! 16..    addresses (INET: src4 dst4 sport dport = 12 bytes; INET6: src16 dst16 sport dport = 36)
//!         then zero or more TLVs: type(1) length(2) value
//! ```
//!
//! ## What the decoder is strict about
//!
//! * The header is bounded ([`MAX_HEADER_LEN`]) before any body byte is read or allocated.
//! * The declared length must cover the address block, and the TLV region must tile exactly: a
//!   TLV that runs past the header, or trailing bytes too short to be a TLV, are refused rather
//!   than skipped, because a lenient parser is what lets a crafted header smuggle bytes.
//! * UNIX families are refused (nothing here is reachable over a unix socket), unspecified and
//!   multicast client addresses are refused, and a protocol that does not match the listener
//!   (datagram header on a stream) is the caller's check via [`Header::transport`].
//! * TLV *contents* are never returned or logged: they are skipped after validation.
//!
//! The decoder reads **exactly** the header from a stream and never a byte more, so the payload
//! that follows is untouched.

use std::net::{IpAddr, Ipv4Addr, Ipv6Addr, SocketAddr};

use tokio::io::{AsyncRead, AsyncReadExt};

/// The 12-byte v2 signature.
pub const SIGNATURE: [u8; 12] = [
    0x0D, 0x0A, 0x0D, 0x0A, 0x00, 0x0D, 0x0A, 0x51, 0x55, 0x49, 0x54, 0x0A,
];
/// Fixed prefix: signature + ver/cmd + fam/proto + length.
pub const PREFIX_LEN: usize = 16;
/// Largest header (prefix + body) this implementation accepts. The spec obliges receivers to
/// accept at least 536 bytes; nothing the LB's peers send needs more.
pub const MAX_HEADER_LEN: usize = 536;
/// Largest header the encoder produces (IPv6 addresses, no TLVs).
pub const MAX_ENCODED_LEN: usize = PREFIX_LEN + 36;

const INET_BLOCK: u16 = 12;
const INET6_BLOCK: u16 = 36;

/// What the header says the connection is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Command {
    /// Health check or similar, generated by the proxy itself: use the real socket endpoints.
    Local,
    /// A relayed connection: the addresses in the header are the original ones.
    Proxy,
}

/// The transport the original connection used.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Transport {
    /// Unspecified or unsupported.
    Unspec,
    /// TCP.
    Stream,
    /// UDP.
    Datagram,
}

/// A decoded header. TLVs are validated and discarded.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Header {
    /// LOCAL or PROXY.
    pub command: Command,
    /// The original transport.
    pub transport: Transport,
    /// `(source, destination)` of the original connection; `None` for LOCAL and UNSPEC, where
    /// the caller must use the real socket endpoints.
    pub addrs: Option<(SocketAddr, SocketAddr)>,
}

/// Why a header was refused. Each variant is a distinct metric label.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ParseError {
    /// The first 12 bytes are not the v2 signature.
    BadSignature,
    /// Version nibble is not 2.
    BadVersion,
    /// Command nibble is not LOCAL or PROXY.
    BadCommand,
    /// Address family or protocol nibble is not one we handle (this includes UNIX).
    BadFamily,
    /// Declared length exceeds [`MAX_HEADER_LEN`].
    TooLong,
    /// Fewer bytes than the prefix or the declared length.
    Truncated,
    /// Declared length is shorter than the address block the family needs.
    BadLength,
    /// The TLV region does not tile exactly.
    BadTlv,
    /// Unspecified or multicast client or destination address.
    BadAddress,
}

impl ParseError {
    /// Stable label for metrics and logs.
    #[must_use]
    pub fn label(self) -> &'static str {
        match self {
            ParseError::BadSignature => "bad_signature",
            ParseError::BadVersion => "bad_version",
            ParseError::BadCommand => "bad_command",
            ParseError::BadFamily => "bad_family",
            ParseError::TooLong => "too_long",
            ParseError::Truncated => "truncated",
            ParseError::BadLength => "bad_length",
            ParseError::BadTlv => "bad_tlv",
            ParseError::BadAddress => "bad_address",
        }
    }
}

impl core::fmt::Display for ParseError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "proxy-protocol v2: {}", self.label())
    }
}

impl std::error::Error for ParseError {}

/// Failure to read a header from a stream.
#[derive(Debug)]
pub enum ReadError {
    /// The bytes were read but are not an acceptable header.
    Parse(ParseError),
    /// The stream ended or errored before a whole header arrived.
    Io(std::io::ErrorKind),
}

impl core::fmt::Display for ReadError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            ReadError::Parse(e) => e.fmt(f),
            ReadError::Io(k) => write!(f, "proxy-protocol v2: read failed ({k})"),
        }
    }
}

impl std::error::Error for ReadError {}

/// An encoded header, on the stack: `len` valid bytes of `buf`.
#[derive(Debug, Clone, Copy)]
pub struct Encoded {
    buf: [u8; MAX_ENCODED_LEN],
    len: usize,
}

impl Encoded {
    /// The header bytes.
    #[must_use]
    pub fn as_bytes(&self) -> &[u8] {
        self.buf.get(..self.len).unwrap_or(&[])
    }
}

fn v6_of(ip: IpAddr) -> Ipv6Addr {
    match ip {
        IpAddr::V4(v4) => v4.to_ipv6_mapped(),
        IpAddr::V6(v6) => v6,
    }
}

/// Encode a PROXY header for a relayed connection `src -> dst`.
///
/// Both ends IPv4 gives the INET block; otherwise both are written as INET6 (an IPv4 end becomes
/// its IPv4-mapped form) because a header carries one family for both addresses.
#[must_use]
pub fn encode(src: SocketAddr, dst: SocketAddr, transport: Transport) -> Encoded {
    let mut buf = [0u8; MAX_ENCODED_LEN];
    buf[..12].copy_from_slice(&SIGNATURE);
    buf[12] = 0x21;
    let proto = match transport {
        Transport::Unspec => 0,
        Transport::Stream => 1,
        Transport::Datagram => 2,
    };
    let len = match (src.ip().to_canonical(), dst.ip().to_canonical()) {
        (IpAddr::V4(s), IpAddr::V4(d)) => {
            buf[13] = 0x10 | proto;
            buf[14..16].copy_from_slice(&INET_BLOCK.to_be_bytes());
            buf[16..20].copy_from_slice(&s.octets());
            buf[20..24].copy_from_slice(&d.octets());
            buf[24..26].copy_from_slice(&src.port().to_be_bytes());
            buf[26..28].copy_from_slice(&dst.port().to_be_bytes());
            PREFIX_LEN + usize::from(INET_BLOCK)
        }
        (s, d) => {
            buf[13] = 0x20 | proto;
            buf[14..16].copy_from_slice(&INET6_BLOCK.to_be_bytes());
            buf[16..32].copy_from_slice(&v6_of(s).octets());
            buf[32..48].copy_from_slice(&v6_of(d).octets());
            buf[48..50].copy_from_slice(&src.port().to_be_bytes());
            buf[50..52].copy_from_slice(&dst.port().to_be_bytes());
            PREFIX_LEN + usize::from(INET6_BLOCK)
        }
    };
    Encoded { buf, len }
}

/// Encode a LOCAL header (no addresses), what a proxy sends for its own probes.
#[must_use]
pub fn encode_local() -> Encoded {
    let mut buf = [0u8; MAX_ENCODED_LEN];
    buf[..12].copy_from_slice(&SIGNATURE);
    buf[12] = 0x20;
    Encoded {
        buf,
        len: PREFIX_LEN,
    }
}

/// The three fields of the 16-byte prefix after validation.
struct Prefix {
    command: Command,
    family: u8,
    transport: Transport,
    body_len: usize,
}

fn parse_prefix(p: &[u8; PREFIX_LEN]) -> Result<Prefix, ParseError> {
    if p[..12] != SIGNATURE {
        return Err(ParseError::BadSignature);
    }
    if p[12] >> 4 != 2 {
        return Err(ParseError::BadVersion);
    }
    let command = match p[12] & 0x0F {
        0 => Command::Local,
        1 => Command::Proxy,
        _ => return Err(ParseError::BadCommand),
    };
    let family = p[13] >> 4;
    let transport = match p[13] & 0x0F {
        0 => Transport::Unspec,
        1 => Transport::Stream,
        2 => Transport::Datagram,
        _ => return Err(ParseError::BadFamily),
    };
    if family > 2 {
        return Err(ParseError::BadFamily);
    }
    let body_len = usize::from(u16::from_be_bytes([p[14], p[15]]));
    if PREFIX_LEN + body_len > MAX_HEADER_LEN {
        return Err(ParseError::TooLong);
    }
    Ok(Prefix {
        command,
        family,
        transport,
        body_len,
    })
}

fn parse_body(prefix: &Prefix, body: &[u8]) -> Result<Header, ParseError> {
    // LOCAL ignores the family and any body: the real endpoints are used. The body is still
    // bounded (already checked) and need not be well formed.
    if prefix.command == Command::Local {
        return Ok(Header {
            command: Command::Local,
            transport: prefix.transport,
            addrs: None,
        });
    }
    let (block, v6) = match prefix.family {
        1 => (usize::from(INET_BLOCK), false),
        2 => (usize::from(INET6_BLOCK), true),
        // UNSPEC with PROXY: accept, use the real endpoints.
        _ => {
            return Ok(Header {
                command: Command::Proxy,
                transport: prefix.transport,
                addrs: None,
            });
        }
    };
    if body.len() < block {
        return Err(ParseError::BadLength);
    }
    let (addr_block, tlvs) = body.split_at(block);
    validate_tlvs(tlvs)?;
    let (src_ip, dst_ip, ports) = if v6 {
        let mut s = [0u8; 16];
        let mut d = [0u8; 16];
        s.copy_from_slice(&addr_block[0..16]);
        d.copy_from_slice(&addr_block[16..32]);
        (
            IpAddr::V6(Ipv6Addr::from(s)),
            IpAddr::V6(Ipv6Addr::from(d)),
            &addr_block[32..36],
        )
    } else {
        let mut s = [0u8; 4];
        let mut d = [0u8; 4];
        s.copy_from_slice(&addr_block[0..4]);
        d.copy_from_slice(&addr_block[4..8]);
        (
            IpAddr::V4(Ipv4Addr::from(s)),
            IpAddr::V4(Ipv4Addr::from(d)),
            &addr_block[8..12],
        )
    };
    let src_ip = src_ip.to_canonical();
    let dst_ip = dst_ip.to_canonical();
    if src_ip.is_unspecified() || src_ip.is_multicast() || dst_ip.is_multicast() {
        return Err(ParseError::BadAddress);
    }
    let sport = u16::from_be_bytes([ports[0], ports[1]]);
    let dport = u16::from_be_bytes([ports[2], ports[3]]);
    Ok(Header {
        command: Command::Proxy,
        transport: prefix.transport,
        addrs: Some((
            SocketAddr::new(src_ip, sport),
            SocketAddr::new(dst_ip, dport),
        )),
    })
}

/// The TLV region must be a whole number of `type(1) len(2) value(len)` records.
fn validate_tlvs(mut tlvs: &[u8]) -> Result<(), ParseError> {
    while !tlvs.is_empty() {
        let Some(head) = tlvs.get(..3) else {
            return Err(ParseError::BadTlv);
        };
        let vlen = usize::from(u16::from_be_bytes([head[1], head[2]]));
        let Some(rest) = tlvs.get(3 + vlen..) else {
            return Err(ParseError::BadTlv);
        };
        tlvs = rest;
    }
    Ok(())
}

/// Decode a header from the start of `buf`, returning it and the number of bytes it occupied.
///
/// # Errors
/// [`ParseError`] when `buf` does not begin with an acceptable v2 header.
pub fn parse(buf: &[u8]) -> Result<(Header, usize), ParseError> {
    let prefix_bytes: &[u8; PREFIX_LEN] = buf
        .get(..PREFIX_LEN)
        .and_then(|s| s.try_into().ok())
        .ok_or(ParseError::Truncated)?;
    let prefix = parse_prefix(prefix_bytes)?;
    let end = PREFIX_LEN + prefix.body_len;
    let body = buf.get(PREFIX_LEN..end).ok_or(ParseError::Truncated)?;
    Ok((parse_body(&prefix, body)?, end))
}

/// Read exactly one header from `r`.
///
/// Reads the 16-byte prefix, validates and bounds the declared length, then reads exactly that
/// many more bytes: never a byte of the payload that follows. The caller applies the timeout.
///
/// # Errors
/// [`ReadError::Parse`] for a bad header, [`ReadError::Io`] if the stream ends first.
pub async fn read_from<R: AsyncRead + Unpin>(r: &mut R) -> Result<Header, ReadError> {
    let mut prefix_bytes = [0u8; PREFIX_LEN];
    r.read_exact(&mut prefix_bytes)
        .await
        .map_err(|e| ReadError::Io(e.kind()))?;
    let prefix = parse_prefix(&prefix_bytes).map_err(ReadError::Parse)?;
    let mut body = [0u8; MAX_HEADER_LEN - PREFIX_LEN];
    let body = body
        .get_mut(..prefix.body_len)
        .ok_or(ReadError::Parse(ParseError::TooLong))?;
    r.read_exact(body)
        .await
        .map_err(|e| ReadError::Io(e.kind()))?;
    parse_body(&prefix, body).map_err(ReadError::Parse)
}

#[cfg(test)]
mod tests {
    #![expect(
        clippy::unwrap_used,
        reason = "test code: deterministic assertions on fixtures"
    )]
    use super::*;

    fn hex(s: &str) -> Vec<u8> {
        let s: String = s.split_whitespace().collect();
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
            .collect()
    }

    // Known-answer vectors written out byte by byte from the spec's layout, independent of the
    // encoder, so a symmetric bug in encode+decode cannot hide.
    const SIG: &str = "0D0A0D0A 000D0A51 5549540A";

    /// TCP over IPv4: 192.168.1.1:56324 -> 192.168.1.2:443.
    fn kat_tcp4() -> Vec<u8> {
        hex(&format!("{SIG} 21 11 000C C0A80101 C0A80102 DC04 01BB"))
    }

    /// TCP over `IPv6`: `[2001:db8::1]:8080 -> [2001:db8::2]:443`.
    fn kat_tcp6() -> Vec<u8> {
        hex(&format!(
            "{SIG} 21 21 0024 20010DB8000000000000000000000001 20010DB8000000000000000000000002 1F90 01BB"
        ))
    }

    /// UDP over IPv4: 203.0.113.9:5353 -> 198.51.100.1:53.
    fn kat_udp4() -> Vec<u8> {
        hex(&format!("{SIG} 21 12 000C CB007109 C6336401 14E9 0035"))
    }

    fn sa(s: &str) -> SocketAddr {
        s.parse().unwrap()
    }

    #[test]
    fn encode_matches_the_known_answers() {
        assert_eq!(
            encode(
                sa("192.168.1.1:56324"),
                sa("192.168.1.2:443"),
                Transport::Stream
            )
            .as_bytes(),
            kat_tcp4()
        );
        assert_eq!(
            encode(
                sa("[2001:db8::1]:8080"),
                sa("[2001:db8::2]:443"),
                Transport::Stream
            )
            .as_bytes(),
            kat_tcp6()
        );
        assert_eq!(
            encode(
                sa("203.0.113.9:5353"),
                sa("198.51.100.1:53"),
                Transport::Datagram
            )
            .as_bytes(),
            kat_udp4()
        );
        assert_eq!(encode_local().as_bytes(), hex(&format!("{SIG} 20 00 0000")));
    }

    #[test]
    fn decode_matches_the_known_answers() {
        let (h, n) = parse(&kat_tcp4()).unwrap();
        assert_eq!(n, 28);
        assert_eq!(h.command, Command::Proxy);
        assert_eq!(h.transport, Transport::Stream);
        assert_eq!(
            h.addrs,
            Some((sa("192.168.1.1:56324"), sa("192.168.1.2:443")))
        );

        let (h, n) = parse(&kat_tcp6()).unwrap();
        assert_eq!(n, 52);
        assert_eq!(
            h.addrs,
            Some((sa("[2001:db8::1]:8080"), sa("[2001:db8::2]:443")))
        );

        let (h, _) = parse(&kat_udp4()).unwrap();
        assert_eq!(h.transport, Transport::Datagram);
        assert_eq!(
            h.addrs,
            Some((sa("203.0.113.9:5353"), sa("198.51.100.1:53")))
        );

        let (h, n) = parse(&hex(&format!("{SIG} 20 00 0000"))).unwrap();
        assert_eq!((h.command, h.addrs, n), (Command::Local, None, 16));
    }

    #[test]
    fn a_mixed_family_pair_is_written_as_v6_with_a_mapped_end() {
        let e = encode(
            sa("192.0.2.1:1000"),
            sa("[2001:db8::2]:443"),
            Transport::Stream,
        );
        assert_eq!(e.as_bytes()[13], 0x21);
        let (h, _) = parse(e.as_bytes()).unwrap();
        // The mapped v4 end is canonicalised back to v4 on decode.
        assert_eq!(
            h.addrs,
            Some((sa("192.0.2.1:1000"), sa("[2001:db8::2]:443")))
        );
    }

    #[test]
    fn encode_then_parse_round_trips() {
        for (s, d, t) in [
            ("1.2.3.4:1", "5.6.7.8:65535", Transport::Stream),
            ("[::1]:9", "[fd00::1]:10", Transport::Datagram),
        ] {
            let e = encode(sa(s), sa(d), t);
            let (h, n) = parse(e.as_bytes()).unwrap();
            assert_eq!(n, e.as_bytes().len());
            assert_eq!(h.addrs, Some((sa(s), sa(d))));
            assert_eq!(h.transport, t);
        }
    }

    #[test]
    fn unknown_tlvs_are_skipped_and_a_well_formed_region_is_accepted() {
        // ALPN "h2" (0x01) then a NOOP (0x04) of 3 bytes: 5 + 6 = 11 extra bytes.
        let v = hex(&format!(
            "{SIG} 21 11 0017 C0A80101 C0A80102 DC04 01BB 010002 6832 040003 AABBCC"
        ));
        let (h, n) = parse(&v).unwrap();
        assert_eq!(n, v.len());
        assert_eq!(
            h.addrs,
            Some((sa("192.168.1.1:56324"), sa("192.168.1.2:443")))
        );
    }

    #[test]
    fn malformed_tlv_regions_are_refused() {
        // A TLV claiming 9 value bytes with only 2 present.
        let v = hex(&format!(
            "{SIG} 21 11 0011 C0A80101 C0A80102 DC04 01BB 010009 6832"
        ));
        assert_eq!(parse(&v), Err(ParseError::BadTlv));
        // Trailing 2 bytes: too short to be a TLV header.
        let v = hex(&format!(
            "{SIG} 21 11 000E C0A80101 C0A80102 DC04 01BB 0102"
        ));
        assert_eq!(parse(&v), Err(ParseError::BadTlv));
    }

    #[test]
    fn every_structural_defect_has_its_own_error() {
        let good = kat_tcp4();
        let mut v = good.clone();
        v[3] ^= 1;
        assert_eq!(parse(&v), Err(ParseError::BadSignature));
        let mut v = good.clone();
        v[12] = 0x11;
        assert_eq!(parse(&v), Err(ParseError::BadVersion));
        let mut v = good.clone();
        v[12] = 0x22;
        assert_eq!(parse(&v), Err(ParseError::BadCommand));
        let mut v = good.clone();
        v[13] = 0x31; // UNIX
        assert_eq!(parse(&v), Err(ParseError::BadFamily));
        let mut v = good.clone();
        v[13] = 0x13; // unknown protocol nibble
        assert_eq!(parse(&v), Err(ParseError::BadFamily));
        let mut v = good.clone();
        v[14] = 0x04; // 1024-byte body
        assert_eq!(parse(&v), Err(ParseError::TooLong));
        let mut v = good.clone();
        v[15] = 0x08; // body shorter than the INET block
        v.truncate(PREFIX_LEN + 8);
        assert_eq!(parse(&v), Err(ParseError::BadLength));
        assert_eq!(parse(&good[..27]), Err(ParseError::Truncated));
        assert_eq!(parse(&good[..5]), Err(ParseError::Truncated));
        // Unspecified client address.
        let v = hex(&format!("{SIG} 21 11 000C 00000000 C0A80102 DC04 01BB"));
        assert_eq!(parse(&v), Err(ParseError::BadAddress));
        // Multicast client address.
        let v = hex(&format!("{SIG} 21 11 000C E0000001 C0A80102 DC04 01BB"));
        assert_eq!(parse(&v), Err(ParseError::BadAddress));
    }

    #[test]
    fn the_v1_text_header_is_not_accepted() {
        let mut v = b"PROXY TCP4 192.168.0.1 192.168.0.11 56324 443\r\n".to_vec();
        v.resize(64, 0);
        assert_eq!(parse(&v), Err(ParseError::BadSignature));
    }

    #[test]
    fn unspec_proxy_and_local_use_real_endpoints() {
        let (h, _) = parse(&hex(&format!("{SIG} 21 00 0000"))).unwrap();
        assert_eq!((h.command, h.addrs), (Command::Proxy, None));
        // LOCAL's body, even if garbage, is ignored (but bounded).
        let (h, n) = parse(&hex(&format!("{SIG} 20 21 0003 AABBCC"))).unwrap();
        assert_eq!((h.command, h.addrs, n), (Command::Local, None, 19));
    }

    #[test]
    fn no_input_panics() {
        // Every prefix and a pile of mutations of a valid header: only Ok/Err, never a panic.
        let good = kat_tcp6();
        for cut in 0..good.len() {
            let _ = parse(&good[..cut]);
        }
        for i in 0..good.len() {
            for bit in 0..8 {
                let mut v = good.clone();
                v[i] ^= 1 << bit;
                let _ = parse(&v);
            }
        }
    }

    #[tokio::test]
    async fn read_from_consumes_exactly_the_header() {
        let mut wire = kat_tcp4();
        wire.extend_from_slice(b"GET / HTTP/1.1\r\n");
        let mut r = &wire[..];
        let h = read_from(&mut r).await.unwrap();
        assert_eq!(h.addrs.unwrap().0, sa("192.168.1.1:56324"));
        assert_eq!(
            r, b"GET / HTTP/1.1\r\n",
            "the payload after the header is untouched"
        );
    }

    #[tokio::test]
    async fn read_from_reports_io_and_parse_failures_distinctly() {
        let wire = kat_tcp4();
        let mut r = &wire[..20];
        assert!(matches!(
            read_from(&mut r).await,
            Err(ReadError::Io(std::io::ErrorKind::UnexpectedEof))
        ));
        let mut r = &b"GET / HTTP/1.1\r\nHost: x\r\n\r\n"[..];
        assert!(matches!(
            read_from(&mut r).await,
            Err(ReadError::Parse(ParseError::BadSignature))
        ));
    }

    #[tokio::test]
    async fn read_from_refuses_an_oversize_length_before_reading_the_body() {
        // Declares a 65535-byte body but supplies none: must fail TooLong, not wait for bytes.
        let mut v = hex(SIG);
        v.extend_from_slice(&[0x21, 0x11, 0xFF, 0xFF]);
        let mut r = &v[..];
        assert!(matches!(
            read_from(&mut r).await,
            Err(ReadError::Parse(ParseError::TooLong))
        ));
    }
}
